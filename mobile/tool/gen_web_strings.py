"""Regenerates lib/l10n/web_strings.dart from the web app's i18n JSON so Android uses identical wording."""
import json, os
root = os.path.join(os.path.dirname(__file__), '..', '..')
def flat(d, p=''):
    o = {}
    for k, v in d.items():
        if isinstance(v, dict): o.update(flat(v, p + k + '.'))
        else: o[p + k] = v
    return o
ns = ['wf', 'sla', 'lost', 'rej', 'profile', 'pw', 'perm', 'orders', 'status', 'ship']
out = ["// GENERATED by tool/gen_web_strings.py from web/src/i18n/{en,zh-CN}.json - do not edit.", "import 'package:flutter/widgets.dart';", "",
       "/// Web-app string by dotted key, `{{x}}` placeholders filled from [args]. Falls back to English, then the key.",
       "String tw(BuildContext context, String key, [Map<String, Object?> args = const {}]) {",
       "  final zh = Localizations.localeOf(context).languageCode == 'zh';",
       "  var s = (zh ? _zh[key] : null) ?? _en[key] ?? key;",
       "  args.forEach((k, v) => s = s.replaceAll('{{$k}}', '${v ?? ''}'));", "  return s;", "}", ""]
for name, f in [('_en', 'en.json'), ('_zh', 'zh-CN.json')]:
    j = json.load(open(os.path.join(root, 'web/src/i18n', f))); m = {}
    for n in ns:
        if n in j: m.update(flat(j[n], n + '.'))
    out.append(f"const {name} = <String, String>{{")
    for k, v in m.items(): out.append(f"  {json.dumps(k)}: {json.dumps(v, ensure_ascii=False).replace('$', chr(92) + '$')},")
    out.append("};")
open(os.path.join(root, 'mobile/lib/l10n/web_strings.dart'), 'w').write('\n'.join(out) + '\n')
